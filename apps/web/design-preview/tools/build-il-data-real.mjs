/* global process, console, URL */
/**
 * Builds `il-data-real.js` (the Internal links mock's real crawl of eventussecurity.com) from the export of
 * `backend/spikes/s18_export.py` (the read API's own answers, kept in a git-ignored folder).
 *
 *   node design-preview/tools/build-il-data-real.mjs <export folder> [output file]
 *
 * Only what the crawl measured is real: pages, links, status, redirects, canonical and indexability, sitemap
 * membership, the crawl run. Clicks, impressions, tracked keywords, citations and mentions are not crawl data, so the
 * real set has none. The page whose path is "/" gets the id "home" because the mock starts its routes there.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const [, , folder, outArg] = process.argv;
if (!folder) {
  console.error('Usage: node build-il-data-real.mjs <export folder> [output file]');
  process.exit(1);
}
const out = outArg ?? join(dirname(fileURLToPath(import.meta.url)), '..', 'il-data-real.js');

const read = (...parts) => JSON.parse(readFileSync(join(folder, ...parts), 'utf8'));
const readDir = (dir) =>
  readdirSync(join(folder, dir))
    .filter((name) => name.endsWith('.json'))
    .sort()
    .flatMap((name) => read(dir, name).data);

const run = read('run.json').data;
const tierList = read('page-tiers.json').data;
const rows = readDir('pages');
const edges = readDir('edges');

const hosts = rows.map((row) => new URL(row.url).host);
const HOST = [...new Set(hosts)].sort((a, b) => hosts.filter((h) => h === b).length - hosts.filter((h) => h === a).length)[0];
// The home page is the "/" of the main host; the "/" of another host (www) is a page of its own
const idOf = (row) => (row.path === '/' && new URL(row.url).host === HOST ? 'home' : `p${row.url_id}`);
const byUrlId = new Map(rows.map((row) => [row.url_id, row]));
const byUrl = new Map(rows.map((row) => [row.url, row]));

const DASHES = new RegExp(`[${String.fromCharCode(0x2013, 0x2014)}]`, 'g');
const pages = rows.map((row) => {
  const redirect = row.redirect_url ? byUrl.get(row.redirect_url) : null;
  return {
    id: idOf(row),
    path: row.path,
    // The repository bans en and em dashes in source text (src/test/source-text.test.ts); crawled titles use them
    title: (row.title ?? '').replace(DASHES, '-'),
    manualTier: null,
    status: row.status_code ?? 0,
    indexable: row.is_indexable !== false,
    reason: row.non_indexable_reason ?? '',
    inSitemap: Boolean(row.in_sitemap),
    tags: [],
    clicks: 0,
    impressions: 0,
    setBy: null,
    setOn: null,
    since: 1,
    ...(redirect ? { redirect: idOf(redirect) } : {}),
    ...(row.canonical_url && row.canonical_url !== row.url ? { canonical: row.canonical_url } : {}),
  };
});

const ids = new Set(pages.map((page) => page.id));
let skipped = 0;
const links = [];
edges.forEach((edge) => {
  const from = byUrlId.get(edge.source.url_id);
  const to = byUrlId.get(edge.target.url_id);
  if (!from || !to) {
    skipped += 1;
    return;
  }
  const nofollow = edge.is_followed === false || edge.rel.includes('nofollow');
  links.push([idOf(from), idOf(to), edge.anchor, edge.placement, nofollow ? 'nofollow' : 'follow']);
});

const data = {
  host: HOST,
  crawledOn: run.finished_at,
  tiers: tierList.map((tier) => ({ id: `tier-${tier.position}`, name: tier.name, description: tier.description })),
  pages,
  links,
  crawl: { pages: pages.length, found: run.pages_found, cost: Number(run.cost_usd), finishedAt: run.finished_at },
};

const header = `/**
 * GENERATED by design-preview/tools/build-il-data-real.mjs from a real DataForSEO crawl of ${data.host}
 * (finished ${run.finished_at}). Do not edit by hand: re-run the tool on a newer export.
 * ${pages.length} pages, ${links.length} links (${skipped} skipped: an end that was not stored).
 */
`;
writeFileSync(resolve(out), `${header}export const REAL = ${JSON.stringify(data)};\n`);
console.log(`${pages.length} pages, ${links.length} links, ${skipped} skipped, ${ids.size} ids -> ${resolve(out)}`);
