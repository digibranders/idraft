/* global process, console, URL */
/**
 * Builds `il-tiers-real.js`: the tiers of the real eventussecurity.com pages, from the tier import file the SEO
 * team's tiers were applied with (a CSV with the header `url,tier`, tier as T1 to T4).
 *
 *   node design-preview/tools/build-il-tiers-real.mjs <tiers.csv> [output file]
 *
 * `il-data-source.js` sets these as manual tiers on the real crawl, so the mock shows the tiers production has.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const [, , csv, outArg] = process.argv;
if (!csv) {
  console.error('Usage: node build-il-tiers-real.mjs <tiers.csv> [output file]');
  process.exit(1);
}
const out = outArg ?? join(dirname(fileURLToPath(import.meta.url)), '..', 'il-tiers-real.js');

const [header, ...rows] = readFileSync(csv, 'utf8').split(/\r?\n/).filter(Boolean);
if (header !== 'url,tier') throw new Error(`Expected the header "url,tier", found "${header}"`);
const tiers = {};
rows.forEach((row, index) => {
  const at = row.lastIndexOf(',');
  const position = /^T([1-9])$/.exec(row.slice(at + 1))?.[1];
  if (!position) throw new Error(`Row ${index + 2}: "${row.slice(at + 1)}" is not a tier (T1 to T9)`);
  tiers[new URL(row.slice(0, at)).pathname] = Number(position);
});

const text = `/**
 * GENERATED by design-preview/tools/build-il-tiers-real.mjs from the tier import file applied in production.
 * Do not edit by hand: re-run the tool on a newer file. ${rows.length} pages. Path to tier position (1 is T1).
 */
export const REAL_TIERS = ${JSON.stringify(tiers)};
`;
writeFileSync(resolve(out), text);
console.log(`${rows.length} pages -> ${resolve(out)}`);
