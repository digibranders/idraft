'use client';

import { useTranslations } from 'next-intl';
import type { ReactElement } from 'react';

import { cn } from '@/lib/utils';

const KEYS = [
  ['pan', 'panWhat'],
  ['space', 'spaceWhat'],
  ['zoom', 'zoomWhat'],
  ['marquee', 'marqueeWhat'],
  ['add', 'addWhat'],
  ['move', 'moveWhat'],
  ['open', 'openWhat'],
  ['arrows', 'arrowsWhat'],
  ['refocus', 'refocusWhat'],
  ['zoomKeys', 'zoomKeysWhat'],
  ['fit', 'fitWhat'],
  ['home', 'homeWhat'],
  ['escape', 'escapeWhat'],
] as const;

const LINES = [
  ['editorial', 'border-foreground-tertiary'],
  ['autoGenerated', 'border-dotted border-border-strong'],
  ['template', 'border-dashed border-border-strong'],
  ['redirect', 'border-warning-text'],
  ['broken', 'border-negative-text'],
  ['back', 'border-dashed border-primary'],
] as const;

const BOXES = [
  ['focus', 'border-primary bg-surface ring-1 ring-primary-border'],
  ['page', 'border-border-strong bg-surface'],
  ['opened', 'border-border-strong bg-primary-subtle'],
  ['shown', 'border-dashed border-border-strong bg-surface'],
  ['group', 'border-border-strong bg-surface-subtle'],
  ['selected', 'border-border-strong bg-surface ring-2 ring-primary'],
] as const;

/**
 * The legend and the controls of the canvas (spec 7.5 "Legend and controls"): the gestures and keys, then what the
 * lines and boxes mean. It replaces the legend row that used to sit under the canvas.
 */
export function CanvasHelp({ id }: { id?: string | undefined }): ReactElement {
  const t = useTranslations('linkCanvas.help');
  const lines = useTranslations('linkCanvas.legend');
  return (
    <div
      id={id}
      role="region"
      aria-label={t('title')}
      data-canvas-control=""
      className="max-h-full w-md max-w-full overflow-auto rounded-lg border border-border bg-surface-elevated p-3 shadow-popover"
    >
      <p className="mb-2 type-body-strong text-foreground">{t('keysTitle')}</p>
      <dl className="grid grid-cols-2 gap-x-4 gap-y-1.5 type-meta">
        {KEYS.map(([keys, what]) => (
          <div key={keys} className="contents">
            <dt className="text-foreground">{t(`keys.${keys}`)}</dt>
            <dd className="text-foreground-secondary">{t(`keys.${what}`)}</dd>
          </div>
        ))}
      </dl>
      <p className="mt-3 mb-2 type-body-strong text-foreground">{t('legendTitle')}</p>
      <div className="flex flex-col gap-2 type-meta text-foreground-secondary">
        <ul aria-label={t('lines')} className="flex flex-wrap items-center gap-x-4 gap-y-1">
          {LINES.map(([key, line]) => (
            <li key={key} className="inline-flex items-center gap-1.5">
              <span aria-hidden="true" className={cn('w-6 border-t-2', line)} />
              {lines(key)}
            </li>
          ))}
        </ul>
        <ul aria-label={t('boxes')} className="flex flex-wrap items-center gap-x-4 gap-y-1">
          {BOXES.map(([key, look]) => (
            <li key={key} className="inline-flex items-center gap-1.5">
              <span aria-hidden="true" className={cn('h-4 w-8 rounded-sm border', look)} />
              {t(`box.${key}`)}
            </li>
          ))}
          <li className="inline-flex items-center gap-1.5">
            <span aria-hidden="true" className="h-4 w-1 rounded-sm bg-foreground-tertiary" />
            {t('box.edge')}
          </li>
        </ul>
      </div>
    </div>
  );
}
