'use client';

import { ArrowDown } from 'lucide-react';
import { useTranslations } from 'next-intl';
import type { ReactElement } from 'react';

import { TierBadge } from '@/components/app/tier/tier-badge';
import { Badge } from '@/components/ui/badge';
import { Icon } from '@/components/ui/icon';
import { routeSteps, type RouteStepView } from '@/lib/internal-links/route-format';
import type { Route } from '@/lib/internal-links/types';

/** The word for a link that is not editorial; editorial links and the first step have none. */
function ScopeWord({ scope }: { scope: RouteStepView['scope'] }): ReactElement | null {
  const t = useTranslations('internalLinks.paths');
  if (scope === 'auto_generated') return <span className="text-foreground-tertiary">{t('scope.autoGenerated')}</span>;
  if (scope === 'template') return <span className="text-foreground-tertiary">{t('scope.template')}</span>;
  return null;
}

/** The link used to reach a step: its words, or the screen's own redirect label (never the backend's English). */
function LinkUsed({ step }: { step: RouteStepView }): ReactElement {
  const t = useTranslations('internalLinks.paths');
  let used: string;
  if (step.viaRedirect) used = t('redirect');
  else if (step.anchor === null || step.anchor.trim() === '') used = t('linkedNoText');
  else used = t('linkedAs', { anchor: step.anchor });
  return (
    <p className="flex flex-wrap items-center gap-2 ps-4 type-meta text-foreground-secondary">
      <Icon icon={ArrowDown} size="sm" className="text-foreground-tertiary" />
      {used}
      {step.viaRedirect ? null : <ScopeWord scope={step.scope} />}
    </p>
  );
}

/** One route from the home page as a chain of step cards, the link used shown between them (spec 7.10). */
export function RouteChain({ title, route }: { title: string; route: Route }): ReactElement {
  const t = useTranslations('internalLinks.paths');
  return (
    <section className="flex min-w-0 flex-col gap-2">
      <h3 className="type-subsection-title">
        {title} <span className="num type-meta text-foreground-secondary">{t('clicks', { count: route.clicks })}</span>
      </h3>
      {/* The role keeps list semantics where the reset of the list style would drop them */}
      <ol role="list" className="flex flex-col gap-1">
        {routeSteps(route).map((step, index) => (
          <li key={step.url_id} className="flex flex-col gap-1">
            {step.first ? null : <LinkUsed step={step} />}
            <div
              aria-current={step.last ? 'step' : undefined}
              className="flex min-w-0 items-center gap-2 rounded-md border border-border bg-surface px-3 py-2"
            >
              <span className="min-w-0 flex-1 truncate type-table text-foreground">{step.path}</span>
              {step.first ? <Badge tone="neutral">{t('home')}</Badge> : null}
              {/* routeSteps keeps the steps in order, so the tier is that of the step at the same place */}
              <TierBadge tier={route.steps[index]?.page.tier ?? null} />
              {step.statusCode !== null && step.statusCode !== 200 ? (
                <Badge tone={step.statusCode >= 400 ? 'negative' : 'warning'}>{String(step.statusCode)}</Badge>
              ) : null}
            </div>
          </li>
        ))}
      </ol>
    </section>
  );
}
