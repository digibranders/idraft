"""The layout catalog the API checks documents against (owner decision D-10; layout spec
sections 6.1, 7 and 9.2).

`catalog.json` is generated by the web from apps/web/src/lib/layouts/catalog.ts
(`pnpm gen:layout-catalog`), never edited. A screen the catalog does not list has no zones yet:
only an empty document can be saved there (plan decision L14). Option contents are the web's to
check; the API knows only that they are a flat object of strings.
"""

from __future__ import annotations

import json
from collections.abc import Mapping
from dataclasses import dataclass, field
from importlib.resources import files
from typing import Annotated, Any, Final, Literal, get_args

from pydantic import BaseModel, ConfigDict, StringConstraints

from idraft.api.problems import FieldError, invalid_fields
from idraft.api.schemas.ai_layouts import CardWidth, LayoutDocument, LayoutScreen

DOCUMENT_MAX_BYTES: Final = 16 * 1024
SCREENS: Final = frozenset(get_args(LayoutScreen))


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


class _Zones(_Strict):
    numbers: bool
    cards: bool
    widths: bool


class _CardType(_Strict):
    key: str
    screens: list[str]
    widths: list[CardWidth]
    status: Literal["active", "retired"]


class _Number(_Strict):
    metric: str
    per_engine: bool
    screens: list[str]


class _Limits(_Strict):
    cards: int
    numbers: int


class CatalogFile(_Strict):
    generated_by: str
    source_sha256: Annotated[str, StringConstraints(pattern=r"^[0-9a-f]{64}$")]
    limits: _Limits
    screens: dict[str, _Zones]
    card_types: list[_CardType]
    numbers: list[_Number]


@dataclass(frozen=True, slots=True)
class ScreenCatalog:
    numbers: bool = False
    cards: bool = False
    # Card type -> the widths it may take on this screen (none on a screen without widths).
    card_widths: Mapping[str, frozenset[str]] = field(default_factory=dict)
    # Metric -> whether it names an engine.
    metrics: Mapping[str, bool] = field(default_factory=dict)


def build(found: CatalogFile) -> dict[str, ScreenCatalog]:
    return {
        screen: ScreenCatalog(
            numbers=zones.numbers,
            cards=zones.cards,
            card_widths={
                card.key: frozenset(card.widths) if zones.widths else frozenset()
                for card in found.card_types
                if screen in card.screens
            },
            metrics={
                number.metric: number.per_engine
                for number in found.numbers
                if screen in number.screens
            },
        )
        for screen, zones in found.screens.items()
    }


FILE: Final = CatalogFile.model_validate_json(
    files("idraft.api.layouts").joinpath("catalog.json").read_text(encoding="utf-8")
)
CATALOG: Final = build(FILE)
_NONE: Final = ScreenCatalog()


def document_errors(
    screen: str, document: LayoutDocument, catalog: Mapping[str, ScreenCatalog] = CATALOG
) -> list[FieldError]:
    allowed = catalog.get(screen, _NONE)
    found: list[FieldError] = []
    if document.numbers and not allowed.numbers:
        found.append(FieldError("numbers", "not_on_screen", "This screen has no headline numbers."))
    else:
        for index, number in enumerate(document.numbers or []):
            per_engine = allowed.metrics.get(number.metric)
            at = f"numbers.{index}"
            if per_engine is None:
                found.append(
                    FieldError(f"{at}.metric", "not_in_catalog", "Not a number of this screen.")
                )
            elif per_engine and number.engine is None:
                found.append(
                    FieldError(f"{at}.engine", "required", "An AI number names its engine.")
                )
            elif not per_engine and number.engine is not None:
                found.append(
                    FieldError(f"{at}.engine", "not_applicable", "Only AI numbers name an engine.")
                )
    if document.cards and not allowed.cards:
        found.append(FieldError("cards", "not_on_screen", "This screen has no cards."))
    else:
        for index, card in enumerate(document.cards or []):
            widths = allowed.card_widths.get(card.type)
            at = f"cards.{index}"
            if widths is None:
                found.append(
                    FieldError(f"{at}.type", "not_in_catalog", "Not a card of this screen.")
                )
            elif card.width is not None and card.width not in widths:
                found.append(
                    FieldError(
                        f"{at}.width", "width_not_allowed", "Not a width this card takes here."
                    )
                )
    return found


def document_size(document: Mapping[str, Any]) -> int:
    """Bytes of the document as PostgreSQL prints a jsonb value: the same separators as
    `json.dumps`, non-ASCII as UTF-8, so the API and the table's check measure the same text."""
    return len(json.dumps(document, ensure_ascii=False).encode())


def stored_document(screen: str, body: LayoutDocument) -> dict[str, Any]:
    """The document as stored, or `422 validation_failed` naming every field found wrong."""
    document = body.model_dump(mode="json", by_alias=True, exclude_none=True)
    if document_size(document) > DOCUMENT_MAX_BYTES:
        raise invalid_fields([FieldError("", "too_large", "A layout is at most 16 KB.")])
    found = document_errors(screen, body)
    if found:
        raise invalid_fields(found)
    return document
