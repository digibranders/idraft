"""Page text for the change hashes (spec 4.2)."""

from __future__ import annotations

from idraft.crawl.page_text import (
    Heading,
    PageText,
    content_hash,
    noncontent_links_of,
    read_page_text,
)
from idraft.crawl.placement import classify

URL = "https://example.com/post"
NONE: frozenset[tuple[str, str]] = frozenset()


def _page(body: str, head: str = "") -> str:
    return f"<html><head>{head}</head><body>{body}</body></html>"


def _hashes(html: str, links: frozenset[tuple[str, str]] = NONE) -> tuple[bytes, bytes]:
    page = read_page_text(html, URL, links)
    return content_hash(page.main_text), content_hash(page.full_text)


def test_reads_title_description_headings_words() -> None:
    html = _page(
        "<main><h1>Big  title</h1><h2>Part</h2><h4>Deep</h4><p>one two three</p></main>",
        '<title> My page </title><meta name="description" content=" About it ">',
    )
    page = read_page_text(html, URL, NONE)
    assert isinstance(page, PageText)
    assert page.title == "My page"
    assert page.description == "About it"
    assert page.headings == (Heading(1, "Big title"), Heading(2, "Part"))
    assert page.words == 7  # Big title Part Deep one two three


def test_caps() -> None:
    many = "".join(f"<h2>h{i}</h2>" for i in range(100))
    page = read_page_text(_page(many + "<h1>" + "x" * 500 + "</h1>"), URL, NONE)
    assert len(page.headings) == 60
    long = read_page_text(_page("<h1>" + "x" * 500 + "</h1>"), URL, NONE)
    assert len(long.headings[0].text) == 200


def test_never_raises_on_garbage() -> None:
    for html in ("", "<<<", "<main><nav>", "</div></div>", "<a href='x'>" * 50, "\x00<p"):
        read_page_text(html, URL, NONE)
    read_page_text("<p>" + "x" * 3_000_000, URL, NONE)


def test_script_style_comment_noscript_template_dropped() -> None:
    a = _page("<p>Hello</p><script>var t=1</script><!-- c1 --><style>p{}</style>")
    b = _page("<p>Hello</p><script>var t=2</script><!-- c2 --><noscript>x</noscript>")
    assert _hashes(a) == _hashes(b)
    assert read_page_text(a, URL, NONE).full_text == "Hello"


def test_cloudflare_email_obfuscation_is_stable() -> None:
    def page(token: str, script: str) -> str:
        return _page(
            f'<p>Mail <a class="__cf_email__" data-cfemail="{token}">[email&#160;protected]</a></p>'
            f"<script>{script}</script>"
        )

    assert _hashes(page("aa11", "var a=1")) == _hashes(page("bb22", "var a=2"))


def test_nav_footer_change_leaves_main_hash() -> None:
    def page(nav: str, foot: str) -> str:
        return _page(f"<nav>{nav}</nav><main><p>Body text</p></main><footer>{foot}</footer>")

    main1, full1 = _hashes(page("Home", "2025"))
    main2, full2 = _hashes(page("Home Blog", "2026"))
    assert main1 == main2
    assert full1 != full2


def test_main_container_choice() -> None:
    both = _page("<p>outside</p><article>A</article><main>M</main><main>M2</main>")
    assert read_page_text(both, URL, NONE).main_text == "M"
    art = _page("<p>outside</p><article>A</article><article>A2</article>")
    assert read_page_text(art, URL, NONE).main_text == "A"
    body = _page("<header>H</header><p>one</p><aside>S</aside><p>two</p><footer>F</footer>")
    assert read_page_text(body, URL, NONE).main_text == "one two"
    nested = _page("<main><aside>side</aside><header>hd</header>keep</main>")
    assert read_page_text(nested, URL, NONE).main_text == "keep"


def test_inline_tags_do_not_split_words() -> None:
    assert (
        read_page_text(_page("<p>fo<b>o</b>bar</p><p>baz</p>"), URL, NONE).main_text == "foobar baz"
    )


def test_autogenerated_link_text_excluded_from_main() -> None:
    html = _page(
        "<main><p>Story</p>"
        '<div><a href="/other">Related story</a> <a href="/mine">Keep me</a></div></main>'
    )
    skip = frozenset({("https://example.com/other", "Related story")})
    page = read_page_text(html, URL, skip)
    assert page.main_text == "Story Keep me"
    assert "Related story" in page.full_text
    assert _hashes(html, skip)[0] != _hashes(html)[0]


def test_noncontent_links_of_uses_classifier() -> None:
    html = _page('<nav><a href="/menu">Menu</a></nav><main><p>x</p><a href="/in">Inline</a></main>')
    links = noncontent_links_of(classify(html, URL))
    assert ("https://example.com/menu", "Menu") in links
    assert ("https://example.com/in", "Inline") not in links


def test_content_hash_normalises_whitespace() -> None:
    assert content_hash("a  b\n c") == content_hash("a b c")
    assert content_hash("a b") != content_hash("a c")
    assert len(content_hash("x")) == 16
